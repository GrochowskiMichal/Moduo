CREATE FUNCTION public.module_api_key_id()
 RETURNS uuid
 LANGUAGE plpgsql
 STABLE
 SET search_path TO 'public'
AS $function$
DECLARE
  v uuid;
BEGIN
  IF coalesce(current_setting('request.jwt.claims', true)::jsonb ->> 'role', '')
     <> 'service_role' THEN
    RETURN NULL;
  END IF;
  BEGIN
    v := nullif(current_setting('request.headers', true)::jsonb ->> 'x-moduo-key-id', '')::uuid;
  EXCEPTION WHEN others THEN
    RETURN NULL;
  END;
  RETURN v;
END;
$function$
;

CREATE FUNCTION public.module_api_key_creator()
 RETURNS uuid
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  SELECT k.created_by
  FROM public.workspace_api_keys k
  WHERE k.id = public.module_api_key_id() AND k.revoked_at IS NULL
$function$
;

CREATE FUNCTION public.perm_actor_id()
 RETURNS uuid
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  SELECT coalesce(auth.uid(), public.module_api_key_creator())
$function$
;

CREATE FUNCTION public.grant_level_rank(p_level text)
 RETURNS integer
 LANGUAGE sql
 IMMUTABLE
AS $function$
  SELECT CASE p_level
    WHEN 'freebusy' THEN 1 WHEN 'view' THEN 2 WHEN 'edit' THEN 3 WHEN 'full' THEN 4
    ELSE 0 END
$function$
;

CREATE FUNCTION public.perm_rank(p_level text)
 RETURNS integer
 LANGUAGE sql
 IMMUTABLE
 SET search_path TO 'public'
AS $function$
  SELECT CASE p_level WHEN 'admin' THEN 3 WHEN 'edit' THEN 2 WHEN 'view' THEN 1 ELSE 0 END
$function$
;

CREATE FUNCTION public.perm_is_owner(p_workspace_id uuid, p_user_id uuid)
 RETURNS boolean
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  SELECT p_user_id IS NOT NULL AND EXISTS (
    SELECT 1 FROM public.workspaces w
    WHERE w.id = p_workspace_id AND w.owner_id = p_user_id AND w.deleted_at IS NULL)
$function$
;

CREATE FUNCTION public.perm_user_has(p_workspace_id uuid, p_user_id uuid, p_key text)
 RETURNS boolean
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  SELECT p_user_id IS NOT NULL AND (
    public.perm_is_owner(p_workspace_id, p_user_id)
    OR EXISTS (SELECT 1 FROM public.workspace_members m
               WHERE m.workspace_id = p_workspace_id AND m.user_id = p_user_id
                 AND p_key = ANY (m.perms)))
$function$
;

CREATE FUNCTION public.perm_ceiling_rank(p_workspace_id uuid, p_user_id uuid, p_module text)
 RETURNS integer
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  SELECT CASE
    WHEN p_user_id IS NULL THEN 0
    WHEN NOT public.perm_user_has(p_workspace_id, p_user_id, p_module || '.view') THEN 0
    WHEN public.perm_user_has(p_workspace_id, p_user_id, p_module || '.delete') THEN 4
    WHEN public.perm_user_has(p_workspace_id, p_user_id, p_module || '.edit') THEN 3
    ELSE 2
  END
$function$
;

CREATE FUNCTION public.share_direct_rank(p_type text, p_id uuid, p_user uuid)
 RETURNS integer
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  SELECT coalesce(max(public.grant_level_rank(g.level)), 0)
  FROM public.resource_grants g
  WHERE g.resource_type = p_type AND g.resource_id = p_id
    AND (
      (g.subject_type = 'member' AND g.subject_id = p_user)
      OR g.subject_type = 'workspace'
    )
$function$
;

CREATE FUNCTION public.can_access(p_type text, p_id uuid, p_min text, p_user uuid DEFAULT NULL::uuid)
 RETURNS boolean
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
  v_user uuid := coalesce(p_user, public.perm_actor_id());
  v_need int := public.grant_level_rank(p_min);
  v_rank int := 0;
  v_ws uuid;
  v_module text;
  v_id uuid;
  v_parent uuid;
  v_mode text;
  v_creator uuid;
  v_system boolean;
  v_bucket uuid;
  v_cal uuid;
  v_guard int := 0;
BEGIN
  IF v_user IS NULL OR p_id IS NULL OR v_need = 0 THEN
    RETURN false;
  END IF;

  IF p_type = 'note' THEN
    v_id := p_id;
    LOOP
      v_guard := v_guard + 1;
      EXIT WHEN v_guard > 100;
      SELECT workspace_id, parent_id, coalesce(share_mode, 'custom'), created_by
        INTO v_ws, v_parent, v_mode, v_creator
      FROM public.notes WHERE id = v_id;
      EXIT WHEN NOT FOUND;
      IF v_creator = v_user THEN v_rank := greatest(v_rank, 4); END IF;
      v_rank := greatest(v_rank, public.share_direct_rank('note', v_id, v_user));
      EXIT WHEN v_mode IS DISTINCT FROM 'inherit' OR v_parent IS NULL;
      v_id := v_parent;
    END LOOP;
    v_module := 'notes';

  ELSIF p_type = 'bucket' THEN
    SELECT workspace_id, owner_id, is_system INTO v_ws, v_creator, v_system
    FROM public.buckets WHERE id = p_id;
    IF NOT FOUND THEN RETURN false; END IF;
    IF v_system THEN
      v_rank := CASE WHEN v_creator = v_user THEN 4 ELSE 0 END;
    ELSE
      IF v_creator = v_user THEN v_rank := 4; END IF;
      v_rank := greatest(v_rank, public.share_direct_rank('bucket', p_id, v_user));
    END IF;
    v_module := 'tasks';

  ELSIF p_type = 'task' THEN
    SELECT workspace_id, bucket_id INTO v_ws, v_bucket FROM public.tasks WHERE id = p_id;
    IF NOT FOUND THEN RETURN false; END IF;
    v_rank := public.share_direct_rank('task', p_id, v_user);
    IF v_bucket IS NOT NULL THEN
      -- Inherit the bucket. Call the rank by re-entering for 'full' then scaling
      -- is wrong; read the bucket rank directly via a nested check's grant.
      IF public.can_access('bucket', v_bucket, 'full', v_user) THEN v_rank := greatest(v_rank, 4);
      ELSIF public.can_access('bucket', v_bucket, 'edit', v_user) THEN v_rank := greatest(v_rank, 3);
      ELSIF public.can_access('bucket', v_bucket, 'view', v_user) THEN v_rank := greatest(v_rank, 2);
      END IF;
    END IF;
    v_module := 'tasks';

  ELSIF p_type = 'calendar' THEN
    SELECT workspace_id, owner_id INTO v_ws, v_creator FROM public.calendars WHERE id = p_id AND deleted_at IS NULL;
    IF NOT FOUND THEN RETURN false; END IF;
    IF v_creator = v_user THEN v_rank := 4; END IF;
    v_rank := greatest(v_rank, public.share_direct_rank('calendar', p_id, v_user));
    v_module := 'calendar';

  ELSIF p_type = 'contact_group' THEN
    SELECT workspace_id, owner_id INTO v_ws, v_creator
    FROM public.contact_groups WHERE id = p_id AND deleted_at IS NULL;
    IF NOT FOUND THEN RETURN false; END IF;
    IF v_creator = v_user THEN v_rank := 4; END IF;
    v_rank := greatest(v_rank, public.share_direct_rank('contact_group', p_id, v_user));
    v_module := 'contacts';

  ELSIF p_type = 'contact' THEN
    SELECT workspace_id, owner_id INTO v_ws, v_creator
    FROM public.contacts WHERE id = p_id AND deleted_at IS NULL;
    IF NOT FOUND THEN RETURN false; END IF;
    IF v_creator = v_user THEN v_rank := 4; END IF;
    v_rank := greatest(v_rank, public.share_direct_rank('contact', p_id, v_user));
    IF EXISTS (
      SELECT 1 FROM public.contact_group_members gm
      JOIN public.contact_groups g ON g.id = gm.group_id AND g.deleted_at IS NULL
      WHERE gm.contact_id = p_id AND public.can_access('contact_group', g.id, 'view', v_user)
    ) THEN
      v_rank := greatest(v_rank, 2);
    END IF;
    IF EXISTS (
      SELECT 1 FROM public.contact_group_members gm
      JOIN public.contact_groups g ON g.id = gm.group_id AND g.deleted_at IS NULL
      WHERE gm.contact_id = p_id AND public.can_access('contact_group', g.id, 'edit', v_user)
    ) THEN
      v_rank := greatest(v_rank, 3);
    END IF;
    v_module := 'contacts';

  ELSIF p_type = 'company' THEN
    SELECT workspace_id, owner_id INTO v_ws, v_creator
    FROM public.companies WHERE id = p_id AND deleted_at IS NULL;
    IF NOT FOUND THEN RETURN false; END IF;
    IF v_creator = v_user THEN v_rank := 4; END IF;
    IF EXISTS (
      SELECT 1 FROM public.contacts c
      WHERE c.company_id = p_id AND c.deleted_at IS NULL
        AND public.can_access('contact', c.id, 'view', v_user)
    ) THEN
      v_rank := greatest(v_rank, 2);
    END IF;
    v_module := 'contacts';

  ELSIF p_type = 'event' THEN
    SELECT workspace_id, owner_id, calendar_ref INTO v_ws, v_creator, v_cal
    FROM public.calendar_events WHERE id = p_id AND deleted_at IS NULL;
    IF NOT FOUND THEN RETURN false; END IF;
    IF v_creator = v_user THEN
      v_rank := 4;
      v_module := 'calendar';
    ELSIF v_cal IS NOT NULL THEN
      RETURN public.can_access('calendar', v_cal, p_min, v_user);
    ELSE
      RETURN false;
    END IF;

  ELSE
    RETURN false;
  END IF;

  IF v_ws IS NULL THEN RETURN false; END IF;
  RETURN least(v_rank, public.perm_ceiling_rank(v_ws, v_user, v_module)) >= v_need;
END;
$function$
;

CREATE FUNCTION public.module_member_permission(p_workspace_id uuid, p_user_id uuid, p_lane text)
 RETURNS text
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
  m public.workspace_members;
  v_mods text[];
BEGIN
  IF p_user_id IS NULL THEN RETURN 'none'; END IF;
  IF public.perm_is_owner(p_workspace_id, p_user_id) THEN RETURN 'admin'; END IF;
  SELECT * INTO m FROM public.workspace_members
   WHERE workspace_id = p_workspace_id AND user_id = p_user_id LIMIT 1;
  IF m.id IS NULL THEN RETURN 'none'; END IF;

  IF p_lane = 'email' THEN
    IF m.role = 'viewer' THEN RETURN 'view'; END IF;
    RETURN CASE lower(coalesce(m.permissions_email, 'edit'))
      WHEN 'none' THEN 'none' WHEN 'read' THEN 'view' WHEN 'view' THEN 'view' ELSE 'edit' END;
  END IF;

  v_mods := CASE WHEN p_lane = 'spine' THEN ARRAY['notes','tasks','calendar','contacts','chat']
                 ELSE ARRAY[p_lane] END;
  IF EXISTS (SELECT 1 FROM unnest(m.perms) k
             WHERE split_part(k, '.', 1) = ANY (v_mods)
               AND split_part(k, '.', 2) IN ('create', 'edit', 'delete')) THEN
    RETURN 'edit';
  END IF;
  IF EXISTS (SELECT 1 FROM unnest(m.perms) k
             WHERE split_part(k, '.', 1) = ANY (v_mods) AND split_part(k, '.', 2) = 'view') THEN
    RETURN 'view';
  END IF;
  RETURN 'none';
END;
$function$
;

CREATE FUNCTION public.module_api_key_scope(p_workspace_id uuid, p_scope_key text, p_lane text)
 RETURNS text
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
  v_key_scope text;
  v_creator   uuid;
  v_member    text;
BEGIN
  SELECT CASE lower(coalesce(k.scopes ->> p_scope_key, 'none'))
           WHEN 'edit' THEN 'edit'
           WHEN 'view' THEN 'view'
           ELSE 'none'
         END,
         k.created_by
    INTO v_key_scope, v_creator
    FROM public.workspace_api_keys k
   WHERE k.id = public.module_api_key_id()
     AND k.workspace_id = p_workspace_id
     AND k.revoked_at IS NULL;

  IF v_key_scope IS NULL OR v_creator IS NULL THEN
    RETURN 'none';
  END IF;

  v_member := public.module_member_permission(p_workspace_id, v_creator, p_lane);
  IF public.perm_rank(v_member) < public.perm_rank(v_key_scope) THEN
    RETURN CASE WHEN v_member = 'view' THEN 'view' ELSE 'none' END;
  END IF;
  RETURN v_key_scope;
END;
$function$
;

