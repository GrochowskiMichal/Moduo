CREATE FUNCTION public.tasks_enforce_one_level_subtasks()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO 'public'
AS $function$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM public.tasks p
    WHERE p.id = NEW.parent_id
      AND p.workspace_id = NEW.workspace_id
      AND p.parent_id IS NULL
  ) THEN
    RAISE EXCEPTION 'Subtasks are one level: the parent must be a top-level task in the same workspace';
  END IF;
  IF EXISTS (
    SELECT 1 FROM public.tasks c
    WHERE c.parent_id = NEW.id
      AND c.deleted_at IS NULL
  ) THEN
    RAISE EXCEPTION 'Subtasks are one level: a task with subtasks cannot become a subtask';
  END IF;
  RETURN NEW;
END;
$function$
;

CREATE FUNCTION public.tasks_relations_mirror_to_links()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
  v_actor uuid;
BEGIN
  IF TG_OP = 'INSERT' THEN
    v_actor := COALESCE(auth.uid(), (SELECT w.owner_id FROM public.workspaces w WHERE w.id = NEW.workspace_id));
    PERFORM public.entities_op_ensure(NEW.workspace_id, 'task', NEW.blocker_task_id,
      (SELECT t.title FROM public.tasks t WHERE t.id = NEW.blocker_task_id), 'task');
    PERFORM public.entities_op_ensure(NEW.workspace_id, 'task', NEW.blocked_task_id,
      (SELECT t.title FROM public.tasks t WHERE t.id = NEW.blocked_task_id), 'task');
    INSERT INTO public.entity_links
      (workspace_id, source_type, source_id, target_type, target_id, relation_kind, origin, created_by)
    VALUES
      (NEW.workspace_id, 'task', NEW.blocker_task_id, 'task', NEW.blocked_task_id, 'blocks', 'manual', v_actor)
    ON CONFLICT (workspace_id, pair_key, relation_kind) WHERE deleted_at IS NULL
    DO NOTHING;
    RETURN NEW;

  ELSIF TG_OP = 'DELETE' THEN
    UPDATE public.entity_links
      SET deleted_at = now()
      WHERE workspace_id = OLD.workspace_id
        AND relation_kind = 'blocks'
        AND deleted_at IS NULL
        AND pair_key = public.spine_pair_key('task', OLD.blocker_task_id, 'task', OLD.blocked_task_id);
    RETURN OLD;
  END IF;
  RETURN NULL;
END;
$function$
;

CREATE FUNCTION public.share_member_removed()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
DECLARE
  v_owner uuid;
  v_name text;
BEGIN
  SELECT owner_id INTO v_owner FROM public.workspaces WHERE id = OLD.workspace_id AND deleted_at IS NULL;
  IF v_owner IS NULL OR v_owner = OLD.user_id THEN RETURN OLD; END IF;
  PERFORM set_config('share.bypass', '1', true);

  -- A non-member can't own a task: perm_enforce_write refuses every later edit
  -- of it ("Viewers can't be assigned tasks"). Unassign instead.
  UPDATE public.tasks SET owner_id = NULL
  WHERE workspace_id = OLD.workspace_id AND owner_id = OLD.user_id;

  DELETE FROM public.resource_grants
  WHERE subject_type = 'member' AND subject_id = OLD.user_id AND workspace_id = OLD.workspace_id;

  -- Account deletion: this cascade runs after the profile is gone. Private
  -- items were erased before it (account_erase_workspace_data); whatever a
  -- deletion outside the app left behind must never reach the owner.
  IF NOT EXISTS (SELECT 1 FROM public.profiles WHERE id = OLD.user_id) THEN
    RETURN OLD;
  END IF;

  SELECT coalesce(nullif(btrim(display_name), ''), 'Member') INTO v_name
  FROM public.profiles WHERE id = OLD.user_id;
  v_name := coalesce(v_name, 'Member');

  UPDATE public.notes SET
    created_by = v_owner,
    title = 'From ' || v_name || ' (archived) ' || title
  WHERE workspace_id = OLD.workspace_id
    AND created_by = OLD.user_id
    AND deleted_at IS NULL
    AND share_mode = 'custom'
    AND NOT EXISTS (
      SELECT 1 FROM public.resource_grants g
      WHERE g.resource_type = 'note' AND g.resource_id = notes.id AND g.subject_type = 'workspace'
    );

  UPDATE public.buckets SET
    owner_id = v_owner,
    name = 'From ' || v_name || ' (archived) ' || name
  WHERE workspace_id = OLD.workspace_id
    AND owner_id = OLD.user_id
    AND deleted_at IS NULL
    AND is_system = false
    AND NOT EXISTS (
      SELECT 1 FROM public.resource_grants g
      WHERE g.resource_type = 'bucket' AND g.resource_id = buckets.id AND g.subject_type = 'workspace'
    );

  RETURN OLD;
END;
$function$
;

