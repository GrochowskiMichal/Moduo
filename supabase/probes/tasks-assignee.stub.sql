             WHERE g.resource_type = p_type AND g.resource_id = p_id
               AND g.subject_type = 'member' AND g.subject_id = m.user_id) ASC NULLS LAST,
           m.joined_at ASC,
           m.user_id
  LIMIT 1;
  RETURN v_pick;
END;
