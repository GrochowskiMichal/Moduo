CREATE FUNCTION public.account_erasure_new_owner(p_type text, p_id uuid, p_workspace_id uuid, p_user uuid)
 RETURNS uuid
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
