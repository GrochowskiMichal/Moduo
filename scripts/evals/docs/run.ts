// The docs eval (specs/harness-v3.md, HV-13, AC32): 46 questions agents asked about Moduo's docs,
// answered with grep in a clone at a fixed commit through the A/B rig, graded by grade.ts. A
// knowledge change (a gotcha compiled into a rule, a split, a deletion) re-runs it on its own commit
// and must score at least the baseline. README.md here.
//
//   bun run eval:docs                        the 46 questions at the baseline commit, compared with the baseline
//   bun run eval:docs --base HEAD            the same questions on this branch's docs (a before/after run)
//   bun run eval:docs score <results.jsonl> [--record]    score a rig batch; --record makes it the baseline
//   bun run eval:docs sync [--check]         regenerate scripts/harness-ab/tasks/docs/ from questions.jsonl

import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";

import type { Row, Task } from "../../harness-ab/model";
import { EVAL_DIR, loadQuestions, type Question } from "./grade";

const ROOT = path.resolve(EVAL_DIR, "../../..");
export const SET = "docs";
export const SET_DIR = path.join(ROOT, "scripts/harness-ab/tasks", SET);
const BASELINE = path.join(EVAL_DIR, "baseline.json");
/** The commit the questions' answers were checked against (origin/mike, 27 Oct 2026). */
export const BASE = "eacbbf7b7dc122067a292cc760e20045eed64e12";
/** One arm, one repeat: the baseline's shape (AC32 compares one score with one score). */
const ARM = "docs";

export const PROMPT_TAIL = [
  "Answer from this repository: its docs, specs, rules and code. Search and read; edit no files.",
  "End with the answer in a few sentences and name the file it comes from.",
  "When the docs hold an older and a newer answer, give the current one.",
  "If the repository doesn't answer the question, say it isn't documented.",
].join(" ");

export function taskFor(q: Question): Task {
  return {
    id: q.id,
    title: q.question,
    source: { note: `docs eval (HV-13), ${q.kind}${q.stale ? ", supersession trap" : ""}` },
    base: BASE,
    prompt: `${q.question}\n\n${PROMPT_TAIL}`,
    expect: "fix",
    install: false,
    // A later base has this eval in it: the agent must not find the answer key.
    hide: ["scripts/evals/docs", `scripts/harness-ab/tasks/${SET}`],
    oracle: {
      checks: [{ name: "grade", run: `bun "$HARNESS_AB_RIG/../evals/docs/grade.ts" ${q.id}` }],
    },
  };
}

const SET_JSON = {
  description:
    "Docs eval (HV-13): 46 questions agents asked about Moduo's docs, graded by scripts/evals/docs/grade.ts. Generated by `bun run eval:docs sync`.",
  verify: null,
};

const json = (v: unknown) => `${JSON.stringify(v, null, 2)}\n`;

/** The task set's files as they should be; `sync` writes them, `sync --check` compares. */
export function setFiles(questions = loadQuestions()): Map<string, unknown> {
  const files = new Map<string, unknown>([["set.json", SET_JSON]]);
  for (const q of questions) files.set(`${q.id}.json`, taskFor(q));
  return files;
}

/** Compared as JSON: `bun fmt` lays the written files out its own way. */
const same = (file: string, want: unknown) =>
  existsSync(file) &&
  JSON.stringify(JSON.parse(readFileSync(file, "utf8"))) === JSON.stringify(want);

/** Files in the set that differ from questions.jsonl, or that it no longer has. */
export function drift(questions = loadQuestions()) {
  const want = setFiles(questions);
  const have = existsSync(SET_DIR) ? readdirSync(SET_DIR).filter((f) => f.endsWith(".json")) : [];
  return {
    write: [...want].filter(([f, body]) => !same(path.join(SET_DIR, f), body)),
    remove: have.filter((f) => !want.has(f)),
  };
}

function sync(check: boolean) {
  const d = drift();
  const n = d.write.length + d.remove.length;
  if (check) {
    for (const f of [...d.write.map(([f]) => f), ...d.remove])
      console.error(`out of date: ${path.relative(ROOT, SET_DIR)}/${f}`);
    if (n) console.error("run `bun run eval:docs sync`");
    return n ? 1 : 0;
  }
  mkdirSync(SET_DIR, { recursive: true });
  for (const [f, body] of d.write) writeFileSync(path.join(SET_DIR, f), json(body));
  for (const f of d.remove) rmSync(path.join(SET_DIR, f));
  if (n) spawnSync("bun", ["fmt", SET_DIR], { cwd: ROOT, stdio: "ignore" });
  console.log(`${n} file(s) changed in ${path.relative(ROOT, SET_DIR)}`);
  return 0;
}

export type Score = {
  score: number;
  pass: number;
  runs: number;
  errors: string[];
  /** Pass share per question across its repeats. */
  questions: Record<string, number>;
};

export function score(rows: Row[]): Score {
  const done = rows.filter((r) => r.outcome === "pass" || r.outcome === "fail");
  const questions: Record<string, number> = {};
  for (const id of [...new Set(done.map((r) => r.task))].sort()) {
    const rs = done.filter((r) => r.task === id);
    questions[id] = rs.filter((r) => r.outcome === "pass").length / rs.length;
  }
  const pass = done.filter((r) => r.outcome === "pass").length;
  return {
    score: done.length ? pass / done.length : 0,
    pass,
    runs: done.length,
    errors: rows.filter((r) => r.outcome === "error" || r.outcome === "planned").map((r) => r.task),
    questions,
  };
}

export type Baseline = Score & {
  base: string;
  arm: string;
  model: string;
  effort: string | null;
  repeats: number;
  batch: string;
  recordedAt: string;
  costUsd: number;
};

/** A run against the baseline: the score may not drop, and every lost question is named. */
export function compare(now: Score, baseline: Pick<Score, "score" | "questions">) {
  const lost = Object.entries(baseline.questions)
    .filter(([id, share]) => (now.questions[id] ?? 0) < share)
    .map(([id]) => id);
  const gained = Object.entries(now.questions)
    .filter(([id, share]) => share > (baseline.questions[id] ?? 0))
    .map(([id]) => id);
  return { ok: now.errors.length === 0 && now.score >= baseline.score, lost, gained };
}

const readRows = (file: string) =>
  readFileSync(file, "utf8")
    .split("\n")
    .filter(Boolean)
    .map((l) => JSON.parse(l) as Row);

const pct = (x: number) => `${(x * 100).toFixed(1)}%`;

function scoreFile(file: string, record: boolean) {
  const rows = readRows(file);
  const s = score(rows);
  console.log(`docs eval: ${s.pass}/${s.runs} = ${pct(s.score)} (${path.relative(ROOT, file)})`);
  if (s.errors.length) console.log(`  errored, not scored: ${s.errors.join(", ")}`);
  const failed = Object.entries(s.questions).filter(([, share]) => share < 1);
  if (failed.length) console.log(`  missed: ${failed.map(([id]) => id).join(", ")}`);
  if (record) {
    if (s.errors.length) {
      console.error("not recorded: re-run the errored questions first");
      return 1;
    }
    const first = rows[0];
    const baseline: Baseline = {
      ...s,
      base: first?.base ?? BASE,
      arm: first?.arm ?? ARM,
      model: first?.model ?? "",
      effort: first?.effort ?? null,
      repeats: Math.max(...rows.map((r) => r.repeat)),
      batch: first?.batch ?? "",
      recordedAt: new Date().toISOString(),
      costUsd: Number(rows.reduce((a, r) => a + (r.agent?.costUsd ?? 0), 0).toFixed(2)),
    };
    writeFileSync(BASELINE, json(baseline));
    console.log(`baseline recorded: ${path.relative(ROOT, BASELINE)}`);
    return 0;
  }
  if (!existsSync(BASELINE)) return 0;
  const baseline = JSON.parse(readFileSync(BASELINE, "utf8")) as Baseline;
  const c = compare(s, baseline);
  console.log(
    `  baseline: ${pct(baseline.score)} at ${baseline.base.slice(0, 9)} (${baseline.batch})`,
  );
  if (c.lost.length) console.log(`  lost since the baseline: ${c.lost.join(", ")}`);
  if (c.gained.length) console.log(`  gained: ${c.gained.join(", ")}`);
  console.log(c.ok ? "OK: at least the baseline" : "BELOW THE BASELINE (or runs errored)");
  return c.ok ? 0 : 1;
}

function run(argv: string[]) {
  const results = path.join(
    process.env.HARNESS_AB_OUT ?? path.join(ROOT, ".harness-ab"),
    "results",
  );
  const before = new Set(existsSync(results) ? readdirSync(results) : []);
  const args = ["run", "--set", SET, "--arms", ARM, "--repeats", "1", "--no-verify", ...argv];
  const r = spawnSync("bun", [path.join(ROOT, "scripts/harness-ab/rig.ts"), ...args], {
    cwd: ROOT,
    stdio: "inherit",
  });
  if (r.status !== 0) return r.status ?? 1;
  if (argv.includes("--dry-run")) return 0;
  const file = readdirSync(results).find((f) => !before.has(f) && f.endsWith(`-${SET}.jsonl`));
  if (!file) throw new Error("the rig wrote no results file");
  return scoreFile(path.join(results, file), false);
}

function main(argv: string[]) {
  const [cmd, ...rest] = argv;
  if (cmd === "sync") return sync(rest.includes("--check"));
  if (cmd === "score") {
    const file = rest.find((a) => !a.startsWith("--"));
    if (!file) throw new Error("usage: score <results.jsonl> [--record]");
    return scoreFile(path.resolve(file), rest.includes("--record"));
  }
  return run(cmd === "run" ? rest : argv);
}

if (import.meta.main) process.exit(main(process.argv.slice(2)));
