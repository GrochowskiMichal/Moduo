/**
 * Builds the notes-doc bundle the MCP connector imports (specs/notes-refresh.md
 * NR-6): `src/features/notes/editor/agent-write.ts` plus Lexical and Yjs, as
 * one dependency-free ES module Deno can load without an import map.
 *
 *   bun run build:notes-doc
 *
 * The header records a hash of every source file that went in; the
 * `notes-doc bundle is current` test fails when the app code changes and the
 * bundle wasn't rebuilt.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { notesDocSourceHash } from "../supabase/functions/_shared/notes-doc/source-hash";

const root = resolve(import.meta.dir, "..");
const entry = resolve(root, "src/features/notes/editor/agent-write.ts");
const out = resolve(root, "supabase/functions/_shared/notes-doc/notes-doc.bundle.js");

const result = await Bun.build({
  entrypoints: [entry],
  target: "browser",
  format: "esm",
  minify: true,
  define: { "process.env.NODE_ENV": '"production"' },
  metafile: true,
});
if (!result.success) {
  for (const log of result.logs) console.error(log);
  process.exit(1);
}
const inputs = Object.keys(result.metafile?.inputs ?? {});
const code = await result.outputs[0]!.text();
const hash = notesDocSourceHash(root, inputs);
const header = [
  "// GENERATED by `bun run build:notes-doc` from src/features/notes/editor/agent-write.ts.",
  "// Do not edit. NR-6: the MCP connector's headless notes-doc writer (Lexical + Yjs).",
  `// source-hash: ${hash}`,
  `// inputs: ${JSON.stringify(inputs.filter((p) => !p.includes("node_modules")).sort())}`,
  "",
].join("\n");
writeFileSync(out, header + code);
console.log(
  `notes-doc bundle: ${(readFileSync(out).byteLength / 1024).toFixed(0)} KB, ${inputs.length} inputs`,
);
